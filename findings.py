import sqlite3
import numpy as np
import pandas as pd

con = sqlite3.connect("credit.db")
scores = pd.read_sql("select * from scores", con, parse_dates=["quarter_end_date"])
fin = pd.read_sql("select * from company_financials", con, parse_dates=["quarter_end_date"])
prices = pd.read_sql("select * from prices", con, parse_dates=["date"])

lines = []


def say(text=""):
    """prints a line and also saves it so it ends up in FINDINGS.md"""
    print(text)
    lines.append(text)


def corr(a, b):
    """correlation between two columns, ignoring blanks. also returns how many rows were used"""
    d = pd.concat([a, b], axis=1).dropna()
    if len(d) < 5:
        return np.nan, len(d)
    return d.iloc[:, 0].corr(d.iloc[:, 1]), len(d)


def small_sample_note(n):
    return "  (small sample, treat as a hint and not proof)" if n < 30 else ""


say("# Findings\n")
say("Generated by findings.py from the project database. Rerun it after refreshing the data.\n")

# 1. does the market's risk level even line up with the company's numbers?
say("## 1. Does market risk follow the fundamentals?")
r, n = corr(scores["z_fund"], scores["z_market"])
say(f"Correlation between fundamental stress and market volatility: {r:.2f} (n={n}){small_sample_note(n)}")
for sec, g in scores.groupby("sector"):
    rs, ns = corr(g["z_fund"], g["z_market"])
    if ns >= 8:
        say(f"- {sec}: {rs:.2f} (n={ns})")
if not np.isnan(r):
    if abs(r) < 0.3:
        say("Market volatility is mostly unrelated to balance sheet stress, which suggests other factors are driving it.")
    elif r > 0.3:
        say("Higher stress companies tend to be more volatile, so the market is roughly following the fundamentals.")
    else:
        say("The correlation is negative: companies with weaker balance sheets are the calmer stocks, the opposite of the expected pattern.")
say()

# 2. does the lease adjustment change who looks the most levered?
say("## 2. Does adding operating lease liabilities change the ranking?")
f = fin.sort_values(["ticker", "quarter_end_date"]).copy()
f["ebitda_ltm"] = f.groupby("ticker")["ebitda"].transform(lambda s: s.rolling(4).sum())
f = f[f["ebitda_ltm"] > 0]
latest_fin = f.groupby("ticker").tail(1).set_index("ticker")
cash = latest_fin["cash_and_equivalents"].fillna(0)


lease = latest_fin["operating_lease_liability"].fillna(0)   # no reported lease liability = nothing added
no_lease = latest_fin.index[latest_fin["operating_lease_liability"].isna()].tolist()


def leverage(extra):
    return (latest_fin["total_debt"] + extra - cash) / latest_fin["ebitda_ltm"]


lev = pd.DataFrame({
    "reported": leverage(0),
    "lease_adjusted": leverage(lease),
})
ranks = lev.rank(ascending=False).astype(int)
say("Net debt / EBITDA rank (1 = most levered), reported debt vs debt plus operating lease liabilities from the filings:")
say(ranks.sort_values("reported").to_string())
moved = (ranks["lease_adjusted"] - ranks["reported"]).abs().sort_values(ascending=False)
if len(moved) > 0 and moved.iloc[0] > 0:
    say(f"Biggest mover is {moved.index[0]}, it moves {moved.iloc[0]} place(s) when lease liabilities are added, so conclusions about it depend on how leases are treated.")
else:
    say("The ranking does not change when lease liabilities are added.")
if no_lease:
    say(f"No operating lease liability found in the filings for: {', '.join(no_lease)} (their adjusted and reported leverage are the same).")
say()

# 3. does a high divergence say anything about what happens next quarter?
say("## 3. Does the divergence score predict anything?")
s = scores.sort_values(["ticker", "quarter_end_date"]).copy()
s["next_vol_change"] = s.groupby("ticker")["vol_30d"].shift(-1) - s["vol_30d"]
s["next_end"] = s.groupby("ticker")["quarter_end_date"].shift(-1)

px = prices.pivot(index="date", columns="ticker", values="close").sort_index()


def price_on(ticker, date):
    """closest price on or before a date (quarter ends are sometimes weekends)"""
    if ticker not in px or pd.isna(date):
        return np.nan
    col = px[ticker].dropna()
    col = col[col.index <= date]
    return col.iloc[-1] if len(col) else np.nan


s["p0"] = [price_on(t, d) for t, d in zip(s["ticker"], s["quarter_end_date"])]
s["p1"] = [price_on(t, d) for t, d in zip(s["ticker"], s["next_end"])]
s["next_return"] = s["p1"] / s["p0"] - 1

for col, name in [("next_return", "next quarter stock return"), ("next_vol_change", "change in volatility next quarter")]:
    rr, nn = corr(s["divergence"], s[col])
    if not np.isnan(rr):
        say(f"Divergence vs {name}: {rr:.2f} (n={nn}){small_sample_note(nn)}")
flag = s[s["label"] == "Review: fundamentals ahead of market"]["next_return"].dropna()
rest = s[s["label"] != "Review: fundamentals ahead of market"]["next_return"].dropna()
if len(flag) >= 3 and len(rest) >= 3:
    say(f"Average next quarter return: flagged companies {flag.mean():.1%} (n={len(flag)}) vs everyone else {rest.mean():.1%} (n={len(rest)})")
say()

# 4. the companies that stand out right now
say("## 4. Who stands out in the latest quarter")
latest = s.groupby("ticker").tail(1).sort_values("divergence", ascending=False)
for _, row in latest.head(3).iterrows():
    say(f"- {row['ticker']} ({row['sector']}): fundamental stress {row['z_fund']:.1f}, market risk {row['z_market']:.1f}, divergence {row['divergence']:.1f}, {row['label']}")
say("Lowest divergence (market risk higher than the balance sheet explains):")
for _, row in latest.tail(3).iterrows():
    say(f"- {row['ticker']} ({row['sector']}): fundamental stress {row['z_fund']:.1f}, market risk {row['z_market']:.1f}, divergence {row['divergence']:.1f}, {row['label']}")
risky = latest[latest["exec_risk"] == 1]["ticker"].tolist()
say(f"Execution risk flags (heavy capex, revenue not keeping up): {', '.join(risky) if risky else 'none'}")

open("FINDINGS.md", "w").write("\n".join(lines) + "\n")
print("\nsaved to FINDINGS.md")
